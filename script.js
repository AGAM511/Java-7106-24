// True 3D globe + compact cursor spider-web. Three.js renders a lit sphere with procedural continents.
(() => {
  const dashboard = document.getElementById('planetDashboard');
  const planet = document.getElementById('interactivePlanet');
  const canvas = document.getElementById('planetCanvas');
  const reticle = document.getElementById('planetReticle');
  const web = document.getElementById('cursorWeb');
  const lat = document.getElementById('planetLat');
  const lng = document.getElementById('planetLng');
  const hint = document.getElementById('dragHint');
  if (!dashboard || !planet || !canvas || !web) return;

  let globe = null, renderer = null, scene = null, camera = null;
  let dragging = false, lastX = 0, lastY = 0;
  let rotX = -.12, rotY = .35;
  const reduced = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
  const NS = 'http://www.w3.org/2000/svg';

  function initGlobe() {
    if (!window.THREE) { planet.classList.add('css-fallback'); return; }
    const T = window.THREE;
    scene = new T.Scene();
    camera = new T.PerspectiveCamera(34, 1, .1, 100);
    camera.position.set(0, 0, 4.1);
    renderer = new T.WebGLRenderer({canvas, alpha:true, antialias:true});
    renderer.setPixelRatio(Math.min(devicePixelRatio || 1, 2));
    renderer.outputColorSpace = T.SRGBColorSpace;
    renderer.setClearColor(0x000000, 0);

    const geometry = new T.SphereGeometry(1, 96, 96);
    const material = new T.ShaderMaterial({
      uniforms: {uTime:{value:0}},
      vertexShader: `varying vec3 vNormal; varying vec3 vPos; varying vec2 vUv; void main(){ vUv=uv; vNormal=normalize(normalMatrix*normal); vec4 mv=modelViewMatrix*vec4(position,1.0); vPos=mv.xyz; gl_Position=projectionMatrix*mv; }`,
      fragmentShader: `
        varying vec3 vNormal; varying vec3 vPos; varying vec2 vUv; uniform float uTime;
        float hash(vec2 p){return fract(sin(dot(p,vec2(127.1,311.7)))*43758.5453);}
        float noise(vec2 p){vec2 i=floor(p),f=fract(p);f=f*f*(3.0-2.0*f);return mix(mix(hash(i),hash(i+vec2(1.,0.)),f.x),mix(hash(i+vec2(0.,1.)),hash(i+vec2(1.,1.)),f.x),f.y);}
        void main(){
          vec3 n=normalize(vNormal); vec3 light=normalize(vec3(-.55,.72,1.0));
          vec2 uv=vec2(vUv.x*9.0,vUv.y*5.0); float land=noise(uv+noise(uv*2.0)*1.7);
          float continent=smoothstep(.53,.61,land);
          float ridge=noise(uv*5.0)*.16;
          vec3 ocean=mix(vec3(.075,.018,.14),vec3(.28,.075,.48),noise(uv*2.2)*.65);
          vec3 ground=mix(vec3(.31,.10,.48),vec3(.83,.48,.95),ridge+noise(uv*1.7)*.22);
          vec3 color=mix(ocean,ground,continent);
          float diffuse=max(dot(n,light),0.0);
          float rim=pow(1.0-max(dot(n,vec3(0.,0.,1.)),0.0),2.6);
          color*=.30+diffuse*.95;
          color+=vec3(.55,.18,.95)*rim*.8;
          float cloud=noise(uv*7.0+uTime*.012); color+=vec3(.38,.16,.52)*smoothstep(.73,.82,cloud)*.22;
          gl_FragColor=vec4(color,1.0);
        }`
    });
    globe = new T.Mesh(geometry, material);
    scene.add(globe);
    const atmosphere = new T.Mesh(new T.SphereGeometry(1.045,64,64), new T.MeshBasicMaterial({color:0xc084fc,transparent:true,opacity:.12,side:T.BackSide}));
    scene.add(atmosphere);
    scene.add(new T.AmbientLight(0xffffff, .8));
    const key = new T.DirectionalLight(0xf2d8ff, 2.1); key.position.set(-3,3,5); scene.add(key);
    const fill = new T.PointLight(0x9b4dff, 2.0, 8); fill.position.set(2,-1,3); scene.add(fill);
    resizeGlobe();
    animateGlobe();
  }
  function resizeGlobe(){
    if(!renderer || !camera) return;
    const r=planet.getBoundingClientRect(); const w=Math.max(1,r.width),h=Math.max(1,r.height);
    renderer.setSize(w,h,false); camera.aspect=w/h; camera.updateProjectionMatrix();
  }
  function animateGlobe(){
    if(!renderer || !globe) return;
    if(!dragging && !reduced) rotY += .0018;
    globe.rotation.x += (rotX-globe.rotation.x)*.18;
    globe.rotation.y += (rotY-globe.rotation.y)*.18;
    globe.material.uniforms.uTime.value += .016;
    renderer.render(scene,camera);
    requestAnimationFrame(animateGlobe);
  }
  function svgEl(tag,attrs){const el=document.createElementNS(NS,tag);for(const [k,v] of Object.entries(attrs))el.setAttribute(k,v);return el;}
  function drawWeb(x,y){
    const r=dashboard.getBoundingClientRect(),w=r.width,h=r.height;
    web.setAttribute('viewBox',`0 0 ${w} ${h}`);web.replaceChildren();
    const g=svgEl('g',{'class':'web-lines'}), radius=Math.min(w,h)*.105, spokes=12;
    const pts=[];
    for(let i=0;i<spokes;i++){const a=Math.PI*2*i/spokes;pts.push([x+Math.cos(a)*radius,y+Math.sin(a)*radius]);g.appendChild(svgEl('line',{x1:x,y1:y,x2:pts[i][0],y2:pts[i][1],stroke:'currentColor','stroke-width':'.8','stroke-opacity':'.55'}));}
    for(let ring=1;ring<=4;ring++){const f=ring/4;for(let i=0;i<spokes;i++){const a=pts[i],b=pts[(i+1)%spokes];g.appendChild(svgEl('line',{x1:x+(a[0]-x)*f,y1:y+(a[1]-y)*f,x2:x+(b[0]-x)*f,y2:y+(b[1]-y)*f,stroke:'currentColor','stroke-width':'.7','stroke-opacity':'.42'}));}}
    const pr=planet.getBoundingClientRect(),cx=pr.left-r.left+pr.width/2,cy=pr.top-r.top+pr.height/2;
    g.appendChild(svgEl('line',{x1:x,y1:y,x2:cx,y2:cy,stroke:'currentColor','stroke-width':'1','stroke-opacity':'.8','stroke-dasharray':'3 5'}));
    g.appendChild(svgEl('circle',{cx:x,cy:y,r:3,fill:'currentColor'}));web.appendChild(g);
  }
  function move(e){
    const r=dashboard.getBoundingClientRect(),x=e.clientX-r.left,y=e.clientY-r.top;
    dashboard.classList.add('is-hovered');if(reticle){reticle.style.left=x+'px';reticle.style.top=y+'px';}drawWeb(x,y);
    if(dragging && globe){const dx=e.clientX-lastX,dy=e.clientY-lastY;rotY+=dx*.009;rotX=Math.max(-1.35,Math.min(1.35,rotX+dy*.009));lastX=e.clientX;lastY=e.clientY;}
    const p=planet.getBoundingClientRect();
    if(lat)lat.textContent=`${(rotX*57.2958).toFixed(1)}°`;
    if(lng)lng.textContent=`${((rotY*57.2958)%360).toFixed(1)}°`;
  }
  dashboard.addEventListener('pointerdown',e=>{if(e.pointerType==='mouse'&&e.button!==0)return;dragging=true;lastX=e.clientX;lastY=e.clientY;dashboard.classList.add('is-dragging');dashboard.setPointerCapture?.(e.pointerId);if(hint)hint.classList.add('dragging');e.preventDefault();});
  dashboard.addEventListener('pointermove',move);
  function stop(){dragging=false;dashboard.classList.remove('is-dragging');if(hint)hint.classList.remove('dragging');}
  dashboard.addEventListener('pointerup',stop);dashboard.addEventListener('pointercancel',stop);
  dashboard.addEventListener('pointerleave',()=>{if(!dragging){dashboard.classList.remove('is-hovered');web.replaceChildren();}});
  window.addEventListener('resize',resizeGlobe);
  initGlobe();
})();
